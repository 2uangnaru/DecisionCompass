def write_multilang_module(path, var_name, data, doc_comment):
    lines = [
        "# coding: utf-8",
        f'"""\n{doc_comment}\n"""',
        "",
        f"{var_name} = {{",
    ]
    for lang in ['zh', 'th', 'hi']:
        lines.append(f"    '{lang}': {{")
        for k in sorted(data[lang].keys()):
            h, s, a = data[lang][k]
            lines.append(f"        '{k}': (")
            lines.append(f"            {repr(h)},")
            lines.append(f"            {repr(s)},")
            lines.append(f"            {repr(a)},")
            lines.append("        ),")
        lines.append("    },")
    lines.append("}")
    lines.append("")
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))

