from build_multilingual_action_guidance import FORBIDDEN_WORDS

def assemble_current(lang):
    combined = {}
    for mod in [universal_data, career_data, love_data, money_data, study_data, friends_data, other_data]:
        combined.update(mod[lang])
    return combined

for lang in ['zh', 'th', 'hi']:
    data = assemble_current(lang)
    forbidden = FORBIDDEN_WORDS[lang]
    print(f"\n--- {lang.upper()} Validation (Total: {len(data)}) ---")
    h_c = Counter(v[0] for v in data.values())
    s_c = Counter(v[1] for v in data.values())
    a_c = Counter(v[2] for v in data.values())
    dup_h = [h for h, c in h_c.items() if c > 1]
    dup_s = [s for s, c in s_c.items() if c > 1]
    dup_a = [a for a, c in a_c.items() if c > 1]
    print(f"  {lang} duplicate headlines: {len(dup_h)}")
    for h in dup_h:
        print(f"    H: {h}")
    print(f"  {lang} duplicate should_dos: {len(dup_s)}")
    for s in dup_s:
        print(f"    S: {s}")
    print(f"  {lang} duplicate avoids: {len(dup_a)}")
    for a in dup_a:
        print(f"    A: {a}")

    fb_hits = []
    for k, (h, s, a) in data.items():
        text = f"{h} {s} {a}"
        for w in forbidden:
            if w in text:
                fb_hits.append((k, w))
    print(f"  {lang} forbidden hits: {len(fb_hits)}")
    for f in fb_hits:
        print(f"    {f}")

    if dup_h or dup_s or dup_a or fb_hits:
        print(f"ERROR: {lang} validation failed!")
        sys.exit(1)

print("\nSUCCESS: ZH, TH, and HI all have 315 keys, 0 duplicates, 0 forbidden words!")

